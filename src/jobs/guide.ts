import { EmbedBuilder } from "discord.js";

/** !وظيفة */
export const JOBS_GUIDE_TRIGGER = /^!\s*وظيفة$/;

const LINES: [string, string][] = [
  ["!وظائف", "لعرض لوحة الوظائف العادية وطلبات التوظيف المفتوحة في الشركات، ومنها تفتح شركتك."],
  ["!وظيفتي", "لعرض وظيفتك الحالية ومستواك وراتبك."],
  ["!دوام", "للدوام في وظيفتك أو شركتك وكسب الراتب أو دعم ميزانية الشركة (كل 3 ساعات)."],
  ["!ترقية", "لطلب الترقية في وظيفتك العادية لو استوفيت الشروط."],
  ["!استقالة", "للاستقالة من وظيفتك أو الخروج من شركتك."],
  ["!شركتي", "لعرض بطاقة شركتك: الميزانية، الرواتب، الفريق، وأزرار الإدارة."],
];

export function buildJobsGuide(): EmbedBuilder {
  return new EmbedBuilder()
    .setColor(0xf1c40f)
    .setTitle("📜 دليل أوامر الوظائف والشركات")
    .setDescription(["إليك قائمة بجميع الأوامر المتاحة في النظام:", "", ...LINES.map(([c, d]) => `🔹 **${c}**\n${d}`)].join("\n"))
    .setFooter({ text: "نظام الوظائف والشركات" });
}
