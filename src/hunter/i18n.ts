export function tr(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = lang === "ar" ? AR[key] : EN[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export const enemyName = (lang: Lang, id: string, fallback: string): string => (lang === "ar" ? ENEMY_AR[id] ?? fallback : fallback);
export const rankName = (lang: Lang, name: string): string => (lang === "ar" ? RANK_AR[name] ?? name : name);
