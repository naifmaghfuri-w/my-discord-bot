import { EmbedBuilder } from "discord.js";

/** يفتح دليل أوامر العائلة بكتابة $Marriage */
export const MARRIAGE_TRIGGER = /^\$marriage$/i;

const COMMANDS: Array<[string, string]> = [
  ["تزوج @منشن مهر 500", "لطلب الزواج من عضو ودفع المهر المحدد (المهر 0 = زواج مجاني)."],
  ["طلاق @منشن", "لإنهاء العلاقة الزوجية من طرف الزوج (وللزوجة: خلع)."],
  ["خلع", "للزوجة: إنهاء الزواج مع إرجاع نصف المهر لزوجها."],
  ["تبني @منشن", "لتبني عضو جديد وضمه لشجرة عائلتك."],
  ["تبرؤ @منشن", "لطرد ابن من العائلة وحذفه من السجلات."],
  ["هروب", "للهروب من العائلة والاستقلال بنفسك."],
  ["شجرة", "لعرض بطاقة شجرة العائلة المصورة (شجرة @منشن لشجرة غيرك)."],
  ["قرابة @منشن", "لكشف صلة القرابة بينك وبين عضو آخر."],
];

export function buildMarriageGuide(): EmbedBuilder {
  return new EmbedBuilder()
    .setColor(0xf5c518)
    .setTitle("📜 دليل أوامر العائلة")
    .setDescription(
      [
        "إليك قائمة بجميع الأوامر المتاحة في النظام:",
        "",
        ...COMMANDS.map(([cmd, desc]) => `🔹 **${cmd}**\n${desc}`),
      ].join("\n"),
    )
    .setFooter({ text: "نظام العائلة" });
}
