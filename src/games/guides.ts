import { EmbedBuilder } from "discord.js";

export type GuideKey = "سالفة" | "كود نايمز";

interface Guide {
  title: string;
  rules: string[];
  rewards?: string[];
}

/** شرح الألعاب الجماعية (يظهر بزر «الشرح» داخل اللعبة) */
const GUIDES: Record<GuideKey, Guide> = {
  سالفة: {
    title: "احزر السالفة",
    rules: [
      "البوت يرسل لجميع الأشخاص نفس الحيوان إلا شخص واحد (برا السالفة).",
      "يجب عليكم المحافظة على الحيوان وعدم كشفه له لكي لا يفوز.",
      "عليكم بسؤال الأسئلة شيء يخص الحيوان الذي ذكر وليس شيء لا يخصه.",
      "على برا السالفة رؤية الأسئلة وأن يحاول معرفة ما الحيوان لكي يفوز.",
      "على الداخل السالفة التصويت على (برا السالفة) عند معرفته.",
      "عندما يتم التصويت على برا السالفة اختيار الحيوان الصحيح لكي يفوز بالجولة.",
    ],
    rewards: ['إذا فاز "برا السالفة" = +3 نقاط عامة', 'إذا فاز "داخل السالفة" = +1 نقطة عامة لكل فائز'],
  },
  "كود نايمز": {
    title: "كود نايمز",
    rules: [
      "ينقسم اللاعبون إلى فريقين (أحمر وأزرق)، ولكل فريق قائد يعطي التلميحات.",
      "القائد يرى لوحة الكلمات السرية بزر «الخريطة السرية»، وفريقه لا يرى إلا الكلمات.",
      "القائد يعطي تلميحاً من كلمة واحدة مع رقم يدل على عدد الكلمات المرتبطة به.",
      "المخمنون يختارون كلمات فريقهم، ولهم تخمينات بعدد الرقم + 1.",
      "إذا اختاروا كلمة الفريق الثاني أو كلمة محايدة ينتهي دورهم.",
      "إذا اختاروا كلمة القاتل 💀 يخسر فريقهم فوراً.",
      "أول فريق يكشف كل كلماته يفوز بالجولة.",
    ],
  },
};

export function guideEmbed(key: GuideKey): EmbedBuilder {
  const g = GUIDES[key];
  const lines = ["**شرح اللعبة:**", ...g.rules.map((r, i) => `${i + 1} : ${r}`)];
  if (g.rewards?.length) lines.push("", "**👥 المكافآت:**", ...g.rewards.map((r) => `• ${r}`));
  return new EmbedBuilder().setColor(0x8b5cf6).setTitle(`🎮 ${g.title}`).setDescription(lines.join("\n"));
}
